# In Ruby, there are different *types* of data:

# Numbers
puts 3
puts 5
puts 3 + 5
puts 3 - 5
puts 3 * 5
puts 5 / 3.0
puts 5 % 3

# Non-numbers
puts "hello, world"

# True, False
puts 3 < 5
puts 3 > 5

# Nothing

# Variables

number_of_taco = 3
number_of_taco_eaters = 5

# Combine strings and variables

puts "we have #{number_of_taco} tacos on special today"

# String manipulation

puts "hello".reverse